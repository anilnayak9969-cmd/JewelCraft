package com.example.JewelCraft.Entites;

import com.example.JewelCraft.Enum.Department;

import jakarta.persistence.*;
import lombok.*;

/** Employment details for STAFF, STORE_MANAGER and ADMIN accounts (for admins, storeBranch is their office). */
@Entity
@Table(name = "staff_profiles")
@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class StaffProfile {

	@Id
	@GeneratedValue(strategy = GenerationType.IDENTITY)
	private Long id;

	@OneToOne(fetch = FetchType.LAZY, optional = false)
	@JoinColumn(name = "user_id", nullable = false, unique = true)
	private User user;

	/** Generated by the server, e.g. JC-ST-0004, JC-SM-0002 or JC-AD-0005. */
	@Column(nullable = false, unique = true, length = 20)
	private String employeeCode;

	/** Staff only; managers run the whole branch. */
	@Enumerated(EnumType.STRING)
	@Column(length = 30)
	private Department department;

	@Column(length = 60)
	private String designation;

	@Column(nullable = false, length = 80)
	private String storeBranch;

	@Column(nullable = false)
	private int experienceYears;

	@Column(length = 100)
	private String qualification;

	@Column(length = 100)
	private String previousEmployer;
}
